                ) {
                    FeaturePill(
                        icon = Icons.Default.People,
                        title = "Student Information System",
                        subtitle = "Admissions, roll lists, batch & section rosters"
                    )
                    FeaturePill(
                        icon = Icons.Default.CheckCircle,
                        title = "Smart Attendance Tracker",
                        subtitle = "Instant batch marking & absent alert logs"
                    )
                    FeaturePill(
                        icon = Icons.Default.Payments,
                        title = "Fee Management & Invoices",
                        subtitle = "Tuition schedules, receipts & revenue analytics"
                    )
                    FeaturePill(
                        icon = Icons.Default.MenuBook,
                        title = "LMS Homework & Exams",
                        subtitle = "Assignments, grading scales & report cards"
                    )
                    FeaturePill(
                        icon = Icons.Default.AutoAwesome,
                        title = "AI Academic Assistant",
                        subtitle = "Instant lesson plans & test question generator"
                    )
                }
            }

            Spacer(modifier = Modifier.height(28.dp))

            if (errorMessage != null) {
                Card(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(bottom = 16.dp),
                    colors = CardDefaults.cardColors(
                        containerColor = MaterialTheme.colorScheme.errorContainer
                    )
                ) {
                    Text(
                        text = errorMessage ?: "",
                        color = MaterialTheme.colorScheme.onErrorContainer,
                        style = MaterialTheme.typography.bodySmall,
                        modifier = Modifier.padding(12.dp),
                        textAlign = TextAlign.Center
                    )
                }
